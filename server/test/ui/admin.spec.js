const { test, expect } = require('@playwright/test');
const path = require('node:path');
for (const width of [1280, 390]) {
  test(`admin player analysis and tactics lab at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.route('https://cdn.socket.io/**', (route) => route.fulfill({ path: path.join(__dirname, '..', '..', 'node_modules/socket.io/client-dist/socket.io.min.js'), contentType: 'application/javascript' }));
    await page.route('https://fonts.googleapis.com/**', (route) => route.abort());
    await page.route('https://fonts.gstatic.com/**', (route) => route.abort());
    await page.route('https://cdn.jsdelivr.net/**', (route) => route.abort());
    await page.goto('/');
    await page.locator('#authUsername').fill('Admin');
    await page.locator('#authPassword').fill(process.env.ADMIN_INITIAL_PASSWORD || 'ui-admin-password');
    await page.locator('#authSubmit').click();
    await expect(page.locator('#btnAdmin')).toBeVisible();
    await expect(page.locator('#btnTactics')).toBeVisible();
    await page.locator('#btnAdmin').click();
    await expect(page.locator('#adminPlayerSummary')).toContainText('510 players');
    await page.locator('#adminPosition').selectOption('FW');
    await page.locator('#adminSearch').fill('Jasir');
    await expect(page.locator('#adminPlayers [data-player]')).toHaveCount(1);
    await page.locator('#adminPlayers [data-player]').click();
    await expect(page.locator('#adminComparison')).toContainText('Jasir Asani');
    await page.locator('#adminSearch').fill('');
    await page.locator('#adminPlayers [data-player][aria-pressed="false"]').first().click();
    await expect(page.locator('#adminComparison thead th')).toHaveCount(3);
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    await page.screenshot({ path: `test-results/admin-${width}.png`, fullPage: true });
    await page.locator('#adminCompetition').selectOption('worldcup');
    await expect(page.locator('#adminPlayerSummary')).toContainText('players');
    await page.locator('#adminPosition').selectOption('');
    await expect(page.locator('#adminPlayerSummary')).toContainText('1248 players');
    await page.locator('#adminTactics').click();
    await expect(page.locator('#tacticTemplate option')).toHaveCount(13);
    await page.locator('#tacticTemplate').selectOption({ label: 'Vertical Tiki-Taka' });
    await expect(page.locator('#tactic-name')).toHaveValue('Vertical Tiki-Taka Custom');
    await page.locator('#tactic-name').fill(`Browser Lab ${width}`);
    await page.locator('#save-tactic').click();
    await expect(page.locator('#tacticVersionNote')).toContainText('Saved version 1');
    await page.locator('#tactic-name').fill(`Browser Revised ${width}`);
    await expect(page.locator('#tacticVersionNote')).toContainText('Unsaved changes');
    await page.locator('#save-tactic').click();
    await expect(page.locator('#tacticVersionNote')).toContainText('Saved version 2');
    await page.locator('#tacticVersions').selectOption('1');
    await page.locator('#restoreTactic').click();
    await expect(page.locator('#tacticVersionNote')).toContainText('Saved version 3');
    await expect(page.locator('#tactic-name')).toHaveValue(`Browser Lab ${width}`);
    await page.locator('#labSamples').selectOption('20');
    await page.locator('#runTacticLab').click();
    await expect(page.locator('#labResults')).toContainText('20 matches per style');
    await expect(page.locator('#labResults')).toContainText('Balanced');
    await expect(page.locator('#labResults tbody tr')).toHaveCount(10);
    await page.screenshot({ path: `test-results/tactics-lab-${width}.png`, fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    await page.locator('#duplicateTactic').click();
    await expect(page.locator('#tactic-name')).toHaveValue(`Browser Lab ${width} Copy`);
    await expect(page.locator('#tacticVersionNote')).toContainText('New tactic');
    await page.getByText('Import Tactic JSON', { exact: true }).click();
    await page.locator('#tacticJSON').fill(JSON.stringify({ tactic: { name: 'Imported Test', attack: 999, defense: .9, id: 99, user_id: 99, version: 50 } }));
    await page.locator('#importTactic').click();
    await expect(page.locator('#tactic-name')).toHaveValue('Imported Test');
    await expect(page.locator('#tacticVersionNote')).toContainText('New tactic');
    expect(Number(await page.locator('#tactic-attack').inputValue())).toBeLessThanOrEqual(1.28);
    expect(errors).toEqual([]);
  });
}
